"""
PANDA access token validation — the init-time token gate (FR-28/FR-29).

This module is the Python implementation of `panda-spec/token-format.md`. The
rule was written out in four implementations, a CLI wizard, `CLAUDE.md`, and
two documentation pages, and one of the copies accepted 48 hex characters
where the rest accepted 48 or 64. It lives in one place now.

Validation has three steps and stops at the first that fails:

1. Presence. An empty token is an error, not a warning.
2. Format. A failure is a warning the caller may override — a user who pasted
   something odd is told, not blocked.
3. Portal. Everything except the demo token is checked against the portal
   before `init` generates a key, and this step is fail-closed.

The SDK source is public, so this gate is for legitimate-usage inventory. It
is not an access-control boundary, and nothing may be protected on the
assumption that a key was only ever generated by an authorised caller. See
Technical PRD Section 14.2.
"""

from __future__ import annotations

import json
import os
import re
import urllib.error
import urllib.request
from typing import Any

from .errors import InvalidTokenError

# The accepted token format: panda_(demo|live)_ followed by 48 or 64 lowercase
# hex characters.
#
# Note the \Z rather than the $ that the other three SDKs write. In Python —
# and in PCRE, so in PHP — `$` also matches immediately before a newline at
# the end of the string, so `panda_demo_<48 a's>\n` matched here and in PHP
# while Node and Go rejected it. A token read from a file or pasted out of a
# heredoc carries a trailing newline routinely, so that was not a theoretical
# difference: the same string was a valid token in two SDKs and not in the
# other two. `\Z` anchors at the end of the string and nothing else, which is
# what the other two engines' `$` already meant. PHP is fixed with the `D`
# modifier, which makes its `$` mean the same.
TOKEN_PATTERN = r"^panda_(demo|live)_([a-f0-9]{48}|[a-f0-9]{64})\Z"

# The static demo token shipped in .env.example and documentation. It is not a
# secret and grants nothing; it exists so a developer can run `init` with no
# portal account.
DEMO_TOKEN = "panda_demo_76d08573d453cdbdb4bf5704d13f8f54d57cd3c47c9b4be2"

# The production portal validation endpoint.
DEFAULT_VALIDATION_URL = "https://csirt.jatimprov.go.id/panda/api/v1/tokens/validate"

# How long to wait for the portal before treating it as unreachable. Short on
# purpose: this is a one-time init step, and a long hang looks like a freeze.
REQUEST_TIMEOUT_SECONDS = 5

# Environments that count as local development rather than deployment.
LOCAL_ENVIRONMENTS = ("local", "dev", "development", "testing")

_TOKEN_RE = re.compile(TOKEN_PATTERN)


def _validation_url() -> str:
    """The validation URL, from the environment or the default."""
    return os.environ.get("PANDA_VALIDATION_URL") or DEFAULT_VALIDATION_URL


def _skip_online_validation() -> bool:
    """Whether the portal call is disabled. For tests only."""
    return os.environ.get("PANDA_SKIP_ONLINE_VALIDATION") == "1"


def is_demo_token(token: str) -> bool:
    """Whether this is the static demo token."""
    return token == DEMO_TOKEN


def is_local_environment() -> bool:
    """
    Whether the current environment looks like local development.

    Used to decide whether to warn about demo token usage. Same rule as the
    other three SDKs: a named production environment is never local, and
    anything unrecognised is treated as local so a developer is not nagged.

    Deliberately conservative in the direction that produces a warning: an
    unset APP_ENV means local, which means the demo-token warning stays quiet
    in development and fires under an explicit deployment environment.
    """
    app_env = os.environ.get("APP_ENV", "").lower()
    if app_env == "production":
        return False
    if os.environ.get("NODE_ENV") == "production":
        return False
    return app_env == "" or app_env in LOCAL_ENVIRONMENTS


def validate_token_format(token: Any) -> bool:
    """
    Whether the token is well-formed.

    Distinct from `validate_token`: that one consults the portal, blocks, and
    raises. This one answers a question about the string — the CLI needs it
    before deciding whether to warn a user that what they typed looks wrong.

    Returns False rather than raising for a non-string, so a caller can pass
    whatever it got from a config file without guarding first.
    """
    if not isinstance(token, str):
        return False
    return _TOKEN_RE.match(token) is not None


def _validate_token_online(token: str) -> None:
    """
    POST the token to the portal. Blocking, and fail-closed.

    Every failure path raises. The one thing this must never do is treat an
    unreachable portal as approval.

    Raises:
        InvalidTokenError: on any failure, including a timeout or a connection
            error — not only on a portal that answers "invalid".
    """
    try:
        payload = json.dumps({"token": token}).encode("utf-8")
    except (TypeError, ValueError) as exc:  # pragma: no cover - str always encodes
        raise InvalidTokenError(
            "Failed to encode validation request. Please try again later."
        ) from exc

    request = urllib.request.Request(
        _validation_url(),
        data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    try:
        with urllib.request.urlopen(request, timeout=REQUEST_TIMEOUT_SECONDS) as response:
            status = response.status
            body = response.read()
    except urllib.error.HTTPError as exc:
        # A response, but not a successful one. Catch this before URLError:
        # HTTPError is a subclass of it, so the wrong order would report a 404
        # as a network failure.
        raise InvalidTokenError(
            f"PANDA portal returned unexpected status code {exc.code}. "
            "Please try again later."
        ) from exc
    except (urllib.error.URLError, OSError) as exc:
        # Covers a refused connection, a DNS failure, a TLS failure, and the
        # socket timeout that urlopen raises when the deadline passes.
        raise InvalidTokenError(
            "Unable to reach the PANDA portal for token validation. "
            "Please check your network connection and try again."
        ) from exc

    if status != 200:
        raise InvalidTokenError(
            f"PANDA portal returned unexpected status code {status}. "
            "Please try again later."
        )

    try:
        result = json.loads(body.decode("utf-8"))
    except (ValueError, UnicodeDecodeError) as exc:
        raise InvalidTokenError(
            "Failed to parse portal response. Please try again later."
        ) from exc

    if not isinstance(result, dict) or "valid" not in result:
        raise InvalidTokenError(
            "Failed to parse portal response. Please try again later."
        )

    # Strictly the boolean true. `if not result["valid"]` was wrong in the
    # dangerous direction: a body of {"valid": "false"} — a string, which is
    # what a proxy or a portal written in a loosely typed language produces —
    # is truthy in Python, so a response saying *no* was read as approval and
    # a key was generated. Only the JSON boolean true is consent; everything
    # else, including "true", falls through to the refusal below.
    if result["valid"] is not True:
        reason = result.get("reason", "invalid")
        if reason == "revoked":
            raise InvalidTokenError(
                "The provided token has been revoked by the portal administrator."
            )
        if reason == "already_activated":
            raise InvalidTokenError(
                "The provided token has already been used. "
                "Each token can only be activated once."
            )
        raise InvalidTokenError(
            "The provided token is invalid or not recognized by the PANDA portal."
        )


def validate_token(token: str) -> None:
    """
    Validate the token, format first and then against the portal.

    The demo token skips the portal entirely — no HTTP request is made — as
    does `PANDA_SKIP_ONLINE_VALIDATION=1`, which is for tests only.

    This is used by `init` and by nothing else. Encrypt, decrypt, mask and
    blind index have no portal dependency (FR-29).

    Raises:
        InvalidTokenError: if the token is missing, empty, malformed, or fails
            portal validation.
    """
    if not token:
        raise InvalidTokenError(
            "A valid PANDA access token is required to initialize a new application.\n"
            "Provide it via --token <value> or the PANDA_ACCESS_TOKEN environment variable.\n"
            "Register your application at the PANDA portal to obtain a token,\n"
            "or use the demo token for local development (see .env.example)."
        )

    if not validate_token_format(token):
        raise InvalidTokenError(
            "The provided token does not match the expected format.\n"
            "Expected: panda_(demo|live)_<48 or 64 hex characters>\n"
            f"Got: {token[:20]}{'...' if len(token) > 20 else ''}"
        )

    # The demo token skips all online validation - no HTTP call is ever made.
    if is_demo_token(token):
        return

    # Test mode: skip online validation when PANDA_SKIP_ONLINE_VALIDATION=1
    if _skip_online_validation():
        return

    # Everything else is checked against the portal. This is blocking and
    # fail-closed: if it fails, init refuses to generate a key.
    _validate_token_online(token)
